<div class="wp-block-column"><!-- wp:list {"ordered":true,"className":"tw-steps"} -->
<ol class="wp-block-list tw-steps"><!-- wp:list-item -->
<li><strong>Check the switchboard.</strong> Electric systems have their own circuit, often labelled HWS. If it has tripped, reset it once. If it trips again, leave it off and call us.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Look at the pilot light.</strong> On a gas storage unit, a pilot that has blown out can usually be relit by following the steps on the unit’s label.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Look under the tank.</strong> Water pooling underneath, or a steady stream from the relief valve drain, needs a plumber. Close the cold water valve at the tank while you wait.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>On off-peak power?</strong> Systems on an off-peak tariff only heat at set times, so a busy morning can empty the tank until the next heating period.</li>
